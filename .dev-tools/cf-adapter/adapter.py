#!/usr/bin/env python3
"""eucli-cf contract=3 adapter for eucli-pueue."""

from __future__ import annotations

import json
import os
import re
import shutil
import socket
import subprocess
import sys
import time
from pathlib import Path

SUFFIX_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
IS_WINDOWS = os.name == "nt"


def emit(payload: dict, code: int) -> None:
    sys.stdout.write(json.dumps(payload, ensure_ascii=False) + "\n")
    sys.stdout.flush()
    raise SystemExit(code)


def ok(data: dict | None = None) -> None:
    out: dict = {"status": "ok"}
    if data is not None:
        out["data"] = data
    emit(out, 0)


def fail(reason: str) -> None:
    emit({"status": "failed", "reason": reason}, 1)


def require_env(name: str) -> str:
    val = os.environ.get(name, "").strip()
    if not val:
        fail(f"缺少必需环境变量 {name}")
    return val


def require_suffix() -> str:
    suffix = require_env("EUCLI_CF_INSTANCE_SUFFIX")
    if not SUFFIX_RE.match(suffix):
        fail(f"实例身份后缀 {suffix!r} 非法，拒绝启动")
    return suffix


def require_port() -> int:
    raw = require_env("EUCLI_CF_PORT_BASE")
    try:
        port = int(raw)
    except ValueError:
        fail(f"端口基址 {raw!r} 非法")
    if port < 1 or port > 65535:
        fail(f"端口基址 {raw!r} 超出范围")
    return port


def exe_name(base: str) -> str:
    return f"{base}.exe" if IS_WINDOWS else base


def cargo_env(deps_store: str, target_dir: Path | None = None) -> dict[str, str]:
    env = os.environ.copy()
    cargo_home = Path(deps_store) / "cargo"
    cargo_home.mkdir(parents=True, exist_ok=True)
    env["CARGO_HOME"] = str(cargo_home)
    if target_dir is not None:
        target_dir.mkdir(parents=True, exist_ok=True)
        env["CARGO_TARGET_DIR"] = str(target_dir)
    return env


def run_cmd(cmd: list[str], cwd: Path, env: dict[str, str]) -> None:
    sys.stderr.write(f"[cf-adapter] ({cwd}) {' '.join(cmd)}\n")
    sys.stderr.flush()
    proc = subprocess.run(cmd, cwd=str(cwd), env=env, stdout=sys.stderr, stderr=sys.stderr)
    if proc.returncode != 0:
        fail(f"命令执行失败 (exit={proc.returncode}): {' '.join(cmd)}")


def bin_dir(build_dir: Path) -> Path:
    return build_dir / "bin"


def config_path(data_root: Path) -> Path:
    return data_root / "pueue.yml"


def pid_path(data_root: Path) -> Path:
    return data_root / "eucli-pueue.pid"


def yaml_str(path: Path) -> str:
    # Use forward slashes inside double-quoted YAML strings for cross-platform safety.
    return json.dumps(path.as_posix())


def write_pueue_config(data_root: Path, port: int, suffix: str) -> Path:
    state_dir = data_root / "state"
    runtime_dir = data_root / "runtime"
    certs_dir = data_root / "certs"
    for d in (data_root, state_dir, runtime_dir, certs_dir):
        d.mkdir(parents=True, exist_ok=True)

    cfg = config_path(data_root)
    lines = [
        f"# Generated by eucli-cf adapter for instance suffix: {suffix}",
        "shared:",
        f"  pueue_directory: {yaml_str(state_dir)}",
        f"  runtime_directory: {yaml_str(runtime_dir)}",
        f"  alias_file: {yaml_str(data_root / 'pueue_aliases.yml')}",
    ]
    if not IS_WINDOWS:
        lines.append("  use_unix_socket: false")
    lines.extend(
        [
            '  host: "127.0.0.1"',
            f'  port: "{port}"',
            f"  pid_path: {yaml_str(runtime_dir / 'pueue.pid')}",
            f"  daemon_cert: {yaml_str(certs_dir / 'daemon.cert')}",
            f"  daemon_key: {yaml_str(certs_dir / 'daemon.key')}",
            f"  shared_secret_path: {yaml_str(certs_dir / 'shared_secret')}",
            "daemon:",
            "  default_parallel_tasks: 2",
            "  pause_group_on_failure: false",
            "  pause_all_on_failure: false",
        ]
    )
    cfg.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return cfg


def is_port_open(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(0.5)
        return s.connect_ex(("127.0.0.1", port)) == 0


def cmd_deps() -> None:
    worktree = Path(require_env("EUCLI_CF_WORKTREE"))
    deps_dir = Path(require_env("EUCLI_CF_DEPS_DIR"))
    deps_store = require_env("EUCLI_CF_DEPS_STORE")
    deps_dir.mkdir(parents=True, exist_ok=True)
    env = cargo_env(deps_store)
    run_cmd(["cargo", "fetch", "--locked"], worktree, env)
    ok()


def cmd_build() -> None:
    worktree = Path(require_env("EUCLI_CF_WORKTREE"))
    build_dir = Path(require_env("EUCLI_CF_BUILD_DIR"))
    deps_store = require_env("EUCLI_CF_DEPS_STORE")
    target_dir = build_dir / "cargo-target"
    env = cargo_env(deps_store, target_dir)

    run_cmd(["cargo", "build", "--locked", "-p", "pueue", "--bins"], worktree, env)

    out_bin_dir = bin_dir(build_dir)
    out_bin_dir.mkdir(parents=True, exist_ok=True)
    built_paths = {}
    for name in ("pueue", "pueued"):
        src = target_dir / "debug" / exe_name(name)
        if not src.is_file():
            fail(f"未找到构建产物: {src}")
        dst = out_bin_dir / exe_name(name)
        shutil.copy2(src, dst)
        built_paths[name] = str(dst)

    ok({"binaries": built_paths})


def cmd_start() -> None:
    suffix = require_suffix()
    port = require_port()
    build_dir = Path(require_env("EUCLI_CF_BUILD_DIR"))
    data_root = Path(require_env("EUCLI_CF_DATA_ROOT"))

    pueued_bin = bin_dir(build_dir) / exe_name("pueued")
    if not pueued_bin.is_file():
        fail(f"正式构建产物不存在: {pueued_bin}")

    cfg = write_pueue_config(data_root, port, suffix)
    log_path = data_root / "pueued.log"

    creationflags = 0
    if IS_WINDOWS:
        creationflags = (
            getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
            | getattr(subprocess, "DETACHED_PROCESS", 0)
            | getattr(subprocess, "CREATE_NO_WINDOW", 0)
        )

    env = os.environ.copy()
    env["PUEUE_CONFIG_PATH"] = str(cfg)
    env["EUCLI_PUEUE_INSTANCE_SUFFIX"] = suffix

    with log_path.open("ab") as log_file:
        proc = subprocess.Popen(
            [str(pueued_bin), "-c", str(cfg)],
            cwd=str(data_root),
            env=env,
            stdin=subprocess.DEVNULL,
            stdout=log_file,
            stderr=log_file,
            close_fds=True,
            creationflags=creationflags,
        )

    pid_path(data_root).write_text(str(proc.pid), encoding="utf-8")
    sys.stderr.write(
        f"[cf-adapter] started eucli-pueue ({suffix}) pid={proc.pid} port={port}\n"
    )
    ok(
        {
            "pid": proc.pid,
            "port": port,
            "suffix": suffix,
            "config": str(cfg),
            "log": str(log_path),
        }
    )


def cmd_health() -> None:
    require_port()
    build_dir = Path(require_env("EUCLI_CF_BUILD_DIR"))
    data_root = Path(require_env("EUCLI_CF_DATA_ROOT"))
    pueue_bin = bin_dir(build_dir) / exe_name("pueue")
    cfg = config_path(data_root)
    if not cfg.is_file():
        fail(f"配置文件不存在: {cfg}")
    if not pueue_bin.is_file():
        fail(f"客户端产物不存在: {pueue_bin}")

    proc = subprocess.run(
        [str(pueue_bin), "-c", str(cfg), "status", "--json"],
        cwd=str(data_root),
        capture_output=True,
        text=True,
        timeout=5,
    )
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip()
        fail(f"pueued 尚未就绪: {detail}")
    try:
        json.loads(proc.stdout)
    except json.JSONDecodeError as exc:
        fail(f"pueue status 输出非合法 JSON: {exc}")
    ok()


def cmd_stop() -> None:
    port = require_port()
    build_dir = Path(require_env("EUCLI_CF_BUILD_DIR"))
    data_root = Path(require_env("EUCLI_CF_DATA_ROOT"))
    pueue_bin = bin_dir(build_dir) / exe_name("pueue")
    cfg = config_path(data_root)

    if pueue_bin.is_file() and cfg.is_file():
        try:
            subprocess.run(
                [str(pueue_bin), "-c", str(cfg), "shutdown"],
                cwd=str(data_root),
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=5,
            )
        except Exception:
            pass

    pfile = pid_path(data_root)
    pid: int | None = None
    if pfile.is_file():
        try:
            pid = int(pfile.read_text(encoding="utf-8").strip())
        except ValueError:
            pid = None

    for _ in range(30):
        if not is_port_open(port):
            pfile.unlink(missing_ok=True)
            ok()
        time.sleep(0.1)

    if pid is not None:
        if IS_WINDOWS:
            subprocess.run(
                ["taskkill", "/F", "/T", "/PID", str(pid)],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
        else:
            try:
                os.kill(pid, 9)
            except ProcessLookupError:
                pass

    for _ in range(50):
        if not is_port_open(port):
            pfile.unlink(missing_ok=True)
            ok()
        time.sleep(0.1)

    fail(f"实例 pid={pid} 在超时内未停止（端口 {port} 仍被占用）")


def cmd_test() -> None:
    worktree = Path(require_env("EUCLI_CF_WORKTREE"))
    build_dir = Path(require_env("EUCLI_CF_BUILD_DIR"))
    data_root = Path(require_env("EUCLI_CF_DATA_ROOT"))
    deps_store = require_env("EUCLI_CF_DEPS_STORE")
    require_port()

    pueue_bin = bin_dir(build_dir) / exe_name("pueue")
    cfg = config_path(data_root)
    if not pueue_bin.is_file() or not cfg.is_file():
        fail("缺少运行中实例的客户端二进制或配置文件")

    # 1. 对运行中正式实例执行队列调度冒烟测试
    sys.stderr.write("[cf-adapter] smoke: pueue add + status wait\n")
    add_proc = subprocess.run(
        [str(pueue_bin), "-c", str(cfg), "add", "--print-task-id", "--", "echo", "eucli-pueue-smoke"],
        cwd=str(data_root),
        capture_output=True,
        text=True,
        timeout=10,
    )
    if add_proc.returncode != 0:
        fail(f"pueue add 失败: {(add_proc.stderr or add_proc.stdout).strip()}")

    task_id = add_proc.stdout.strip()
    done = False
    for _ in range(60):
        st_proc = subprocess.run(
            [str(pueue_bin), "-c", str(cfg), "status", "--json"],
            cwd=str(data_root),
            capture_output=True,
            text=True,
            timeout=5,
        )
        if st_proc.returncode == 0:
            payload = json.loads(st_proc.stdout)
            task = payload.get("tasks", {}).get(task_id)
            if task and isinstance(task.get("status"), dict) and "Done" in task["status"]:
                result = task["status"]["Done"].get("result")
                if result != "Success":
                    fail(f"冒烟任务 {task_id} 执行失败: {result}")
                done = True
                break
        time.sleep(0.2)

    if not done:
        fail(f"冒烟任务 {task_id} 在超时内未完成")

    subprocess.run(
        [str(pueue_bin), "-c", str(cfg), "clean"],
        cwd=str(data_root),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        timeout=5,
    )

    # 2. 跑核心库单元测试（隔离 target 到运行区，不污染工作树）
    env = cargo_env(deps_store, build_dir / "cargo-target")
    run_cmd(["cargo", "test", "--locked", "-p", "pueue-lib", "--lib"], worktree, env)
    ok()


def main() -> None:
    if len(sys.argv) < 2:
        fail("缺少适配器子命令")
    sub = sys.argv[1]
    handlers = {
        "deps": cmd_deps,
        "build": cmd_build,
        "start": cmd_start,
        "health": cmd_health,
        "stop": cmd_stop,
        "seed": lambda: emit({"status": "not-applicable"}, 0),
        "test": cmd_test,
    }
    fn = handlers.get(sub)
    if fn is None:
        fail(f"未知适配器子命令: {sub}")
    try:
        fn()
    except SystemExit:
        raise
    except Exception as exc:
        fail(f"适配器执行异常: {exc}")


if __name__ == "__main__":
    main()
